const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const read=f=>fs.readFileSync(path.resolve(__dirname,f),'utf8');
const html=read('index.html'),css=read('camera-story.css'),live=html.replace(/<noscript>[\s\S]*?<\/noscript>/g,'');
assert.match(html,/<title>[^<]*V10.128<\/title>/);
assert.doesNotMatch(html+css+read('camera-story.js')+read('paper-tail.js'),/paper-memo|--memo-alpha|Keepsake Notes|memo.woff2|先把笑容准备好|下一张合影/);
assert.equal([...live.matchAll(/<script src="[^"]+" defer/g)].length,1);
const manifest=JSON.parse(read('bundle-manifest.json'));
const expected='/* V10.128: ordered deferred runtime bundle. */\n'+manifest.map(name=>';\n/* Source: '+name+' */\n'+read(name)).join('\n');
assert.equal(read('opening-runtime.js').trim(),expected.trim());new vm.Script(read('opening-runtime.js'));
assert.ok(manifest.indexOf('instant-paper.js')<manifest.indexOf('camera-story-math.js'));
for(const name of ['page-media.js','handoff-math.js'])assert.equal(read(name),read('../v10.125-keepsake-fast/'+name),'Unrelated controller unchanged');
assert.equal(html.match(/<style id="camera-runtime-style">([\s\S]*?)<\/style>/)[1].trim(),css.trim());
const photos=[...live.matchAll(/<img[^>]*data-media-src="[^"]*\/media\/couple-1600.webp"[^>]*>/g)];
assert.equal(photos.length,2);assert.equal((live.match(/class="instant-paper"/g)||[]).length,2);
for(const [tag]of photos){assert.match(tag,/data-media-sizes="\(max-width: 1000px\) 64vw, 640px"/);assert.match(tag,/960w[^"]*1600w[^"]*2400w/);assert.doesNotMatch(tag,/\ssrc="/);}
assert.match(css,/\.instant-paper[^}]*background:#fffdf8/);
assert.match(css,/\.instant-paper \.camera-photo[^}]*outline:none/);
const windowRule=css.match(/\.instant-paper \.camera-photo\{([^}]+)\}/)[1];
const value=k=>Number(windowRule.match(new RegExp(k+':([\\d.]+)%'))[1]);
const left=value('left'),top=value('top'),width=value('width'),height=value('height');
assert.ok(Math.abs(left-(100-left-width))<1e-8,'Equal left/right borders');
assert.ok(Math.abs(left-top*.75)<1e-8,'Top and side borders have equal physical thickness');
assert.ok((100-top-height)*.75>left*2.5,'Characteristic wide white lower border');
assert.ok(Math.abs((width/(height*.75))-(28.4/(12.2*1.5)))<1e-8,'Original photo crop ratio remains intact');
for(const [,src]of html.matchAll(/(?:src|href|data-src|data-media-src)="([^"#]+)"/g))if(!/^(https?:|data:)/.test(src))assert.ok(fs.existsSync(path.resolve(__dirname,src.split('?')[0])),src);
for(const [,src]of css.matchAll(/url\("([^"]+)"\)/g))assert.ok(fs.existsSync(path.resolve(__dirname,src)),src);
const pre=html.match(/<link rel="preload"[^>]+>/)[0],picture=html.match(/<source srcset="[^>]+>/)[0];
assert.equal(pre.match(/imagesrcset="([^"]+)"/)[1],picture.match(/srcset="([^"]+)"/)[1]);
assert.equal(pre.match(/imagesizes="([^"]+)"/)[1],picture.match(/sizes="([^"]+)"/)[1]);
assert.ok(Buffer.byteLength(read('opening-runtime.js'))-Buffer.byteLength(read('../v10.125-keepsake-fast/opening-runtime.js'))<6000,'Small runtime addition; no animation library');
const report=JSON.parse(read('asset-report.json'));
assert.ok(report.filter(r=>/camera-(art|clean)/.test(r.out)).every(r=>r.pixelsEqual));
