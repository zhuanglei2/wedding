const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const read=f=>fs.readFileSync(path.join(__dirname,f),'utf8');
const html=read('index.html'),css=read('camera-story.css'),old=path.resolve(__dirname,'../v10.124-brighter-flash');
const live=html.replace(/<noscript>[\s\S]*?<\/noscript>/g,'');
assert.equal([...live.matchAll(/<script src="[^"]+" defer/g)].length,1);
assert.match(live,/<script src="opening-runtime.js" defer><\/script>/);
const manifest=JSON.parse(read('bundle-manifest.json'));
const expected='/* V10.125: ordered deferred runtime bundle. */\n'+manifest.map(name=>';\n/* Source: '+name+' */\n'+read(name)).join('\n');
assert.equal(read('opening-runtime.js').trim(),expected.trim(),'Bundled code exactly equals ordered sources');
new vm.Script(read('opening-runtime.js'));
for(const file of ['camera-story-math.js','handoff-math.js','page-turn.js'])assert.equal(read(file),fs.readFileSync(path.join(old,file),'utf8'));
assert.equal(html.match(/<style id="camera-runtime-style">([\s\S]*?)<\/style>/)[1].trim(),css.trim());
assert.equal((html.match(/class="paper-memo paper-memo--top"/g)||[]).length,2);
assert.match(css,/opacity:var\(--memo-alpha,1\)/);
assert.match(read('camera-story.js'),/setStyle\(root,'--memo-alpha',String\(state.names\)\)/);
assert.match(read('paper-tail.js'),/head-headBlend>=88&&tail-blend>=88/);
assert.match(css,/html\.cover-first \.paper-memo\{display:none!important\}/);
const photos=[...live.matchAll(/<img[^>]*data-media-src="media\/couple-1600.webp"[^>]*>/g)];
assert.equal(photos.length,2);
for(const [tag]of photos){assert.match(tag,/width="4000" height="6000"/);assert.match(tag,/data-media-srcset="[^"]*960w[^"]*1600w[^"]*2400w"/);assert.doesNotMatch(tag,/\ssrc="/);}
assert.match(read('page-media.js'),/if\(sizes\)image.sizes=sizes;\s*if\(srcset\)image.srcset=srcset;\s*image.loading='eager';image.src=src;/);
const pre=html.match(/<link rel="preload"[^>]+>/)[0],picture=html.match(/<source srcset="[^>]+>/)[0];
assert.equal(pre.match(/imagesrcset="([^"]+)"/)[1],picture.match(/srcset="([^"]+)"/)[1]);
assert.equal(pre.match(/imagesizes="([^"]+)"/)[1],picture.match(/sizes="([^"]+)"/)[1]);
const report=JSON.parse(read('asset-report.json'));
for(const name of ['camera-art.webp','camera-clean.webp'])assert.equal(report.find(r=>r.out===name).pixelsEqual,true);
assert.ok(fs.statSync(path.join(__dirname,'memo.woff2')).size<30000,'Tiny local font, not the complete 6MB family');
const before=report.filter(r=>['camera-art.webp','camera-clean.webp','couple-960.webp'].includes(r.out)).reduce((a,r)=>a+r.originalBytes,0);
const after=report.filter(r=>['camera-art.webp','camera-clean.webp','couple-960.webp'].includes(r.out)).reduce((a,r)=>a+r.bytes,0);
assert.ok(after<before*.40,'Over 60% saved on these second-page image resources');
console.log('PASS: exact ordered runtime bundle, responsive media selection/preload, original layout and clocks, lossless paper, tiny font, gated notes and image byte budgets. Not a network-speed or browser-visual measurement.');
